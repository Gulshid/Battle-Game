/// cos(angle) * [kTrigScale].
int cosOf(int angle) => _cosTable[angle & 255];

/// sin(angle) * [kTrigScale]. Positive means "down" (screen space).
int sinOf(int angle) => _sinTable[angle & 255];

/// Floor of the square root of [n] (0 for n <= 0). Pure integer Newton.
int isqrt(int n) {
  if (n <= 0) return 0;
  var x = 1 << ((n.bitLength + 1) >> 1); // always >= sqrt(n)
  while (true) {
    final y = (x + n ~/ x) >> 1;
    if (y >= x) return x;
    x = y;
  }
}

/// The byte angle whose direction best matches the vector (dx, dy).
/// Ties go to the lower angle. (0, 0) returns 0.
int angleOf(int dx, int dy) {
  if (dx == 0 && dy == 0) return 0;
  var best = 0;
  var bestDot = dx * _cosTable[0] + dy * _sinTable[0];
  for (var a = 1; a < kAngleSteps; a++) {
    final dot = dx * _cosTable[a] + dy * _sinTable[a];
    if (dot > bestDot) {
      bestDot = dot;
      best = a;
    }
  }
  return best;
}

/// Shortest distance between two byte angles, 0..128.
int angleDiff(int a, int b) {
  final d = (a - b) & 255;
  return d > 128 ? 256 - d : d;
}
